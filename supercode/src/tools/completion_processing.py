def validate_asserts(language, code, entry_point, canonical_solution):
    """Check if the examples generated by the LLM are correct, if not replace the output or remove the example."""
    if verbose>0: print(">> extracting test code")

    # find all the asserts using the func name (entry_point), assuming either:
    # --> assert function_name(input) == output, f"expected..."
    # --> assert abs(function_name(input) - output) < 1e-6, f"expected..."
    pattern = entry_point+r'assert (abs\()?(below_zero)\(([^\\n]*)\)\s(==|-)\s([^\\n<]*)(\) < 1e-6)?, f?[\'\"]'
    matches = re.findall(pattern, code)

    io_list = []
    for match in matches:
        io_list.append([match.group(2), match.group(4)]) # input/output pair for each assert

    val_code = print_canon_io(language, entry_point, canonical_solution, io_list)
    sandboxed_compiler(val_code, language, unit_test=None, entry_point=None, k_times=1)

    canon_output = eval(f"{canonical_solution}\n{entry_point}({match.group(1)})")
    if canon_output != match.group(2):
        code.replace(match.group(2), canon_output)

    return code

